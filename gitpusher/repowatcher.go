type RepoWatcher struct {
	config         *RepoConfig
	dirPath        string
	abfsClient     remote.RemoteProvider
	remoteName     string
	pushedRefsFile string
	shgit          *shellgit.ShellGit
	gitRepo        *git.Repository

	// statMu guards state, listStart, listDuration, lastSuccess and lastErr,
	// which Stat reads while ListProjects runs.
	statMu           sync.Mutex
	state            RepoWatcherState
	listStart        time.Time
	listDuration     time.Duration
	lastSuccess      time.Time
	lastErr          error
	lastManifestRead time.Time
	lastReport       atomic.Pointer[listingReport]
}

type RepoWatcherState int

const (
	RepoWatcherCreated RepoWatcherState = iota
	RepoWatcherInitialized
	RepoWatcherSleep
	RepoWatcherFetch
	RepoWatcherManifestRead
)

func (s RepoWatcherState) String() string {
	switch s {
	case RepoWatcherCreated:
		return "created"
	case RepoWatcherInitialized:
		return "initialized"
	case RepoWatcherSleep:
		return "sleep"
	case RepoWatcherFetch:
		return "fetch"
	case RepoWatcherManifestRead:
		return "manifest-read"
	default:
		return fmt.Sprintf("unknown state: %d", s)
	}
}

func newRepoWatcher(config *RepoConfig, g *GitPusher) ProjectLister {
	dirPath := path.Join(g.projectStoragePath, "manifest", config.Manifest.Server, config.Manifest.Project+".git")

	return &RepoWatcher{
		config:         config,
		dirPath:        dirPath,
		remoteName:     defaultRemoteName,
		abfsClient:     g.limitedRemote,
		pushedRefsFile: path.Join(dirPath, pushedRefsFile),
		shgit:          g.shgit,
	}
}

// Stat implements ProjectLister.
func (m *RepoWatcher) setState(state RepoWatcherState) {
	m.statMu.Lock()
	defer m.statMu.Unlock()
	m.state = state
}

func (m *RepoWatcher) Stat() RepoStat {
	m.statMu.Lock()
	defer m.statMu.Unlock()
	lastErr := ""
	if m.lastErr != nil {
		lastErr = m.lastErr.Error()
	}
	stat := RepoStat{
		Name:          m.config.Name(),
		Remote:        m.config.Manifest.Server,
		URL:           m.config.Manifest.URL,
		State:         m.state.String(),
		FetchStart:    m.listStart.Format(time.RFC3339),
		FetchDuration: m.listDuration.Seconds(),
		LastSuccess:   m.lastSuccess.Format(time.RFC3339),
		LastError:     lastErr,
	}
	if r := m.lastReport.Load(); r != nil {
		stat.ManifestFiles, stat.Skipped = r.read, r.skipped
	}
	return stat
}

// writeGitConfig fetches every branch of the manifest repository. A refspec that names one missing
// branch would fail the whole fetch.
func (m *RepoWatcher) writeGitConfig() error {
	template := `# Generated by GitPusher
[core]
	repositoryformatversion = 0
	filemode = true
	bare = true
[remote "%s"]
	url = %s
	tagOpt = --no-tags
	fetch = +refs/heads/*:refs/remotes/%s/*
`
	config := fmt.Sprintf(template, m.remoteName, m.config.Manifest.URL, m.remoteName)

	return os.WriteFile(path.Join(m.dirPath, "config"), []byte(config), 0644)
}

func (m *RepoWatcher) init() error {
	r, err := getOrCreateGitRepo(m.dirPath)
	if err != nil {
		return err
	}
	m.gitRepo = r

	if err := m.writeGitConfig(); err != nil {
		return err
	}

	m.setState(RepoWatcherInitialized)
	return nil
}

// ListProjects implements ProjectLister.
func (m *RepoWatcher) ListProjects(ctx context.Context) (projects []*ProjectConfig, err error) {
	defer func() {
		m.statMu.Lock()
		defer m.statMu.Unlock()
		m.lastErr = err
	}()

	if m.state == RepoWatcherCreated {
		if err := m.init(); err != nil {
			return nil, err
		}
	}

	m.statMu.Lock()
	m.listStart = time.Now()
	m.statMu.Unlock()
	defer func() {
		m.statMu.Lock()
		defer m.statMu.Unlock()
		m.listDuration = time.Since(m.listStart)
		m.state = RepoWatcherSleep
	}()

	m.setState(RepoWatcherFetch)
	if err := fetchWithRetry(m.shgit, m.dirPath); err != nil {
		return nil, err
	}

	// get a new repo object so it doesn't use cached data
	manifestRepo, err := getOrCreateGitRepo(m.dirPath)
	if err != nil {
		return nil, err
	}
	m.gitRepo = manifestRepo

	m.lastManifestRead = time.Now()

	report := &listingReport{}
	// Parse the manifest in (name, remote, url) groupings.
	// We later drop the remote portion.
	allProjects, err := m.manifestProjects(report)
	if err != nil {
		return nil, err
	}

	manProject := projectRemoteSchemeURL{
		name:   m.config.Manifest.Project,
		server: m.config.Manifest.Server,
		url:    m.config.Manifest.URL,
	}
	result := make([]*ProjectConfig, 0, len(allProjects)+1)
	// The scheduler keeps one config per project name, so the first manifest file that lists a project
	// decides its URL. Later variants are reported, not pushed.
	added := make(map[ProjectName]*ProjectConfig, len(allProjects)+1)
	addProject := func(project projectRemoteSchemeURL, source string) error {
		fetchConfig, excluded := m.config.ProjectFetchConfig(project.name)
		if excluded {
			return nil
		}

		p := &ProjectConfig{
			Project:     project.name,
			Server:      project.server,
			URL:         instance.MaybeAddScheme(project.url, project.scheme),
			FetchConfig: fetchConfig,
		}
		if err := p.Validate(); err != nil {
			if project == manProject {
				return err
			}
			report.skip(fmt.Sprintf("%s: project %s: %v", source, project.name, err))
			return nil
		}
		if first, found := added[p.Name()]; found {
			if first.URL != p.URL {
				report.skip(fmt.Sprintf("%s: project %s also listed as %s", source, p.Name(), p.URL))
			}
			return nil
		}
		added[p.Name()] = p
		result = append(result, p)
		return nil
	}

	if err := addProject(manProject, "manifest url"); err != nil {
		return nil, err
	}

	for _, project := range allProjects {
		if err := addProject(project.projectRemoteSchemeURL, project.source); err != nil {
			return nil, err
		}
	}

	m.logReport(report)
	m.statMu.Lock()
	m.lastSuccess = time.Now()
	m.statMu.Unlock()
	return result, nil
}

// listingReport lists the manifest files a listing read and what it skipped.
type listingReport struct {
	read    []string
	skipped []string
}

func (r *listingReport) skip(s string) {
	r.skipped = append(r.skipped, s)
}

func (m *RepoWatcher) logReport(r *listingReport) {
	last := m.lastReport.Load()
	if last == nil || !slices.Equal(last.read, r.read) {
		log.Printf("Repo %s reads %s", m.config.Name(), strings.Join(r.read, ", "))
	}
	for _, s := range r.skipped {
		if last == nil || !slices.Contains(last.skipped, s) {
			log.Printf("Repo %s skipped %s", m.config.Name(), s)
		}
	}
	m.lastReport.Store(r)
}

// manifestProject is a project and the manifest file that listed it.
type manifestProject struct {
	projectRemoteSchemeURL
	source string
}

// manifestBranches returns the commit of every fetched manifest branch.
func (m *RepoWatcher) manifestBranches() (map[string]plumbing.Hash, error) {
	refs, err := m.gitRepo.References()
	if err != nil {
		return nil, err
	}
	prefix := "refs/remotes/" + m.remoteName + "/"
	branches := make(map[string]plumbing.Hash)
	err = refs.ForEach(func(ref *plumbing.Reference) error {
		if branch, ok := strings.CutPrefix(ref.Name().String(), prefix); ok && ref.Type() == plumbing.HashReference {
			branches[branch] = ref.Hash()
		}
		return nil
	})
	return branches, err
}

// manifestProjects returns the projects of every manifest file, in the order of the manifest files
// in the config and, for a branch pattern, of the branch names. A manifest file that cannot be read
// is skipped and reported, so it does not stop the projects of the others.
func (m *RepoWatcher) manifestProjects(report *listingReport) ([]manifestProject, error) {
	branches, err := m.manifestBranches()
	if err != nil {
		return nil, err
	}
	names := slices.Sorted(maps.Keys(branches))

	var result []manifestProject
	for _, manifestSpec := range m.config.Manifest.Files {
		matched := false
		for _, branch := range names {
			if !manifestSpec.MatchesBranch(branch) {
				continue
			}
			matched = true
			source := branch + ":" + manifestSpec.File

			branchCommit, err := m.gitRepo.CommitObject(branches[branch])
			if err != nil {
				report.skip(fmt.Sprintf("%s: %v", source, err))
				continue
			}
			contentor := &objectContentor{branchCommit}

			// A file that cannot be read from the clone fails the listing, so its projects are not dropped.
			var readErr *manifestReadError
			if _, err := contentor.Contents(manifestSpec.File); errors.As(err, &readErr) {
				return nil, err
			} else if err != nil {
				report.skip(source + ": no such file")
				continue
			}

			mappings, err := projectMappingsForFile(contentor, m.config.Manifest.URL, manifestSpec.File)
			if errors.As(err, &readErr) {
				return nil, err
			} else if err != nil {
				report.skip(fmt.Sprintf("%s: %v", source, err))
				continue
			}
			set := make(map[projectRemoteSchemeURL]struct{})
			if err := mappings.updateProjectRemoteURLSet(set); err != nil {
				report.skip(fmt.Sprintf("%s: %v", source, err))
				continue
			}
			projects := slices.SortedFunc(maps.Keys(set), func(a, b projectRemoteSchemeURL) int {
				return strings.Compare(a.String(), b.String())
			})
			for _, project := range projects {
				result = append(result, manifestProject{project, source})
			}
			report.read = append(report.read, source)
		}
		switch {
		case matched:
		case manifestSpec.isPattern():
			report.skip(manifestSpec.Branch + ": no matching branch")
		default:
			report.skip(manifestSpec.Branch + ": no such branch")
		}
	}

	return result, nil
}

// contentor is an interface to read the contents of a manifest file.
type contentor interface {
	Contents(string) (string, error)
}

// forAllManifests visits the manifest tree in a DFS pre-order fashion and executes the provided function.
func forAllManifests(contentor contentor, manifestFile string, onParse func(*manifest.Manifest) error) error {
	const notParsed = -1

	type stackEntry struct {
		manifestFile string
		includes     []*manifest.Include
		currInc      int
	}

	stack := []*stackEntry{
		{
			manifestFile: manifestFile,
			currInc:      notParsed,
		},
	}

	seen := make(map[string]bool)
	for len(stack) != 0 {
		// Peek at top of the stack.
		entry := stack[len(stack)-1]

		// Parse the node if we haven't yet.
		if entry.currInc == notParsed {
			contents, err := contentor.Contents(entry.manifestFile)
			if err != nil {
				return err
			}

			man, err := manifest.Parse([]byte(contents))
			if err != nil {
				return fmt.Errorf("failed to parse file %q as a manifest file: %w", entry.manifestFile, err)
			}

			if err := onParse(man); err != nil {
				return err
			}

			entry.includes = man.Include
			entry.currInc = 0
		}

		// Pop this entry from the stack if we're on the last child.
		if len(entry.includes) == 0 || entry.currInc == len(entry.includes)-1 {
			stack = stack[:len(stack)-1]
		}

		// Add next child.
		if entry.currInc < len(entry.includes) {
			inc := entry.includes[entry.currInc]
			entry.currInc++
			if seen[inc.Name] {
				continue
			}
			seen[inc.Name] = true

			stack = append(stack, &stackEntry{
				manifestFile: inc.Name,
				currInc:      notParsed,
			})
		}
	}

	return nil
}

// projectRemote pairs a project name with a remote name.
type projectRemote struct {
	// Name of the remote (not the resolved URL)
	// Empty string implies default
	remote string

	// Per repo docs: the URL will be the concatenation of {Remote URL, name.git}
	name string
}

// projectMappings contain project and remote mappings.
type projectMappings struct {
	// Name of the default Remote (not the resolved URL)
	defaultRemote string

	// Map the name of the remote to the resolved URL
	remotes map[string]string

	projectRemotes map[projectRemote]struct{}
}

// projectRemoteSchemeURL contains the necessary information needed to create a directory and fetch from a remote URL.
// We track scheme here because this is a manifest-layer data structure, and consumers need the scheme information to create remotes.
type projectRemoteSchemeURL struct {
	name   string
	server string
	remote string
	scheme string
	url    string
}

func (p *projectRemoteSchemeURL) String() string {
	return p.name + p.remote + p.scheme + p.url
}

// updateProjectRemoteURLSet updates the input set with new values from the state of ProjectMappings.
func (p *projectMappings) updateProjectRemoteURLSet(set map[projectRemoteSchemeURL]struct{}) error {
	for projectRemote := range p.projectRemotes {
		remote := projectRemote.remote
		if remote == "" {
			remote = p.defaultRemote
		}

		remoteSchemeURL := p.remotes[remote]
		resolvedSchemeURL, err := url.JoinPath(remoteSchemeURL, projectRemote.name)
		if err != nil {
			return err
		}
		u, err := url.Parse(resolvedSchemeURL)
		if err != nil {
			return err
		}

		pru := projectRemoteSchemeURL{
			name:   projectRemote.name,
			server: instance.Host(resolvedSchemeURL),
			remote: remote,
			scheme: u.Scheme,
			url:    instance.MaybeRemoveScheme(resolvedSchemeURL),
		}
		set[pru] = struct{}{}
	}

	return nil
}

// projectMappingsForFile returns project and remote mappings discovered from parsing a manifest tree.
func projectMappingsForFile(contentor contentor, manifestURL string, manifestFile string) (projectMappings, error) {
	remotes := make(map[string]string)
	projectRemotes := make(map[projectRemote]struct{})

	projectMappings := projectMappings{
		remotes:        remotes,
		projectRemotes: projectRemotes,
	}
	baseSchemeURL, err := url.Parse(manifestURL)
	if err != nil {
		return projectMappings, err
	}
	numDefaults := 0

	err = forAllManifests(contentor, manifestFile, func(m *manifest.Manifest) error {
		// Grab all the remotes.
		for _, remote := range m.Remote {
			fetchSchemeURL, err := url.Parse(remote.Fetch)
			if err != nil {
				return err
			}
			// This matches the Python urljoin behavior that the repo tool uses.
			resolvedSchemeURL := baseSchemeURL.ResolveReference(fetchSchemeURL)
			if curr, found := remotes[remote.Name]; found {
				if curr != resolvedSchemeURL.String() {
					return fmt.Errorf("duplicate remote found with different fetch url. Original: %q, Duplicate: %q", curr, resolvedSchemeURL)
				}
			} else {
				remotes[remote.Name] = resolvedSchemeURL.String()
			}
		}

		// Check for default.
		if m.Default != nil {
			numDefaults++
			if numDefaults > 1 {
				return errors.New("more than one default element found")
			}

			projectMappings.defaultRemote = m.Default.Remote
		}

		for _, project := range m.Project {
			projectRemotes[projectRemote{
				name:   project.Name,
				remote: project.Remote,
			}] = struct{}{}
		}

		return nil
	})

	return projectMappings, err
}

// objectContentor reads a manifestFile contents at a specific commit.
type objectContentor struct {
	commit *object.Commit
}

func (o *objectContentor) Contents(manifestFile string) (string, error) {
	if o.commit == nil {
		return "", errors.New("commit is nil")
	}
	file, err := o.commit.File(manifestFile)
	if err != nil {
		err = fmt.Errorf("failed to find file %q at commit with hash %q: %w", manifestFile, o.commit.Hash, err)
		if errors.Is(err, object.ErrFileNotFound) {
			return "", err
		}
		return "", &manifestReadError{err}
	}

	contents, err := file.Contents()
	if err != nil {
		return "", &manifestReadError{fmt.Errorf("failed to read file %q at commit with hash %q: %w", manifestFile, o.commit.Hash, err)}
	}
	return contents, nil
}

// manifestReadError is a failure to read the manifest clone, as opposed to a file the branch does not have.
type manifestReadError struct {
	err error
}

func (e *manifestReadError) Error() string {
	return e.err.Error()
}

func (e *manifestReadError) Unwrap() error {
	return e.err
}
